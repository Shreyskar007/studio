
import type { Meeting } from '@/hooks/use-meetings';

export const generateMeetingLink = (platform: Meeting['platform'], meetingId: string) => {    
    switch (platform) {
        case 'Google Meet':
            // Google Meet uses a lookup code, which is essentially the meeting ID without dashes.
            return `https://meet.google.com/lookup/${meetingId.replace(/-/g, '')}`;
        case 'Zoom':
            // Zoom uses the meeting ID directly in the join URL.
            return `https://zoom.us/j/${meetingId}`;
        case 'Microsoft Teams':
             // Teams links are more complex and usually generated by their API.
             // This is a simplified, predictable placeholder format.
            return `https://teams.microsoft.com/l/meetup-join/v2/mock/${meetingId}`;
    }
}
